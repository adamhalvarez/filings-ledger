import type { MetadataRoute } from "next";
import { entityDirectory, entityPeriods } from "@/lib/db";
import { SITE_URL } from "@/lib/site";
import { BUILD_TIME } from "@/lib/format";

// Generated at build time from the same directory queries the filings pages
// use, so a sitemap cannot list a page that was not built or miss one that
// was. Written by hand rather than left to a crawler to discover: the
// filings pages are a directory more than a hundred entries deep, several
// levels down from the front page, which is exactly the shape a crawler
// gives up on partway through.
//
// lastModified is the build time for every entry, which is honest at the
// level this site actually operates: every page here is regenerated by the
// same daily build, so no page has a modification date of its own that
// differs from any other. Claiming a per page date would be inventing
// precision this model does not have.
export default async function sitemap(): Promise<MetadataRoute.Sitemap> {
  const now = BUILD_TIME;
  const entities = await entityDirectory();

  const fixed = ["", "/watchlist", "/confluence", "/filings", "/search", "/methodology", "/aliases", "/license"];

  const entries: MetadataRoute.Sitemap = fixed.map((path) => ({
    url: `${SITE_URL}${path}`,
    lastModified: now,
  }));

  for (const e of entities) {
    entries.push({ url: `${SITE_URL}/filings/${e.slug}`, lastModified: now });
    if (!e.large) continue;
    for (const p of await entityPeriods(e.canonical_name)) {
      entries.push({
        url: `${SITE_URL}/filings/${e.slug}/${p.label}`,
        lastModified: now,
      });
    }
  }

  // /filings/unmatched is absent on purpose, the same decision middleware.ts
  // and robots.ts make; so is /data/, for the reason robots.ts gives.
  return entries;
}
